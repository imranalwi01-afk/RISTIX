# 3. Generate Auth Provider
generate_auth_provider() {
    local file_path="${ADMIN_DIR}/providers/auth/authProvider.ts"
    local content='// ============================================================================
// PSDD ARTIFACT DOCUMENTATION
// ============================================================================
// File Path: packages/frontend/src/admin/providers/auth/authProvider.ts
// Generated: Generated by D2H5 - React Admin Foundation
// Phase: D2H5 - React Admin Foundation
// Methodology: Phased Shell-Driven Development (PSDD)
// Dependencies: React Admin AuthProvider, JWT tokens, RBAC
// Purpose: Banking RBAC authentication provider with multi-tenant support
// ============================================================================

import { AuthProvider, UserIdentity } from "react-admin";

const API_BASE_URL = process.env.NEXT_PUBLIC_API_BASE_URL || "http://localhost:4232/api";

interface AuthResponse {
  token: string;
  user: {
    id: string;
    username: string;
    email: string;
    full_name: string;
    roles: Array<{
      id: string;
      role_name: string;
      permissions: Record<string, boolean>;
    }>;
  };
  tenant: {
    id: string;
    tenant_name: string;
    banking_type: "conventional" | "syariah" | "dual";
    features_enabled: Record<string, boolean>;
  };
}

export const authProvider: AuthProvider = {
  // Login with username/password
  login: async ({ username, password, tenantSlug }) => {
    try {
      const response = await fetch(`${API_BASE_URL}/auth/login`, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          username,
          password,
          tenant_slug: tenantSlug,
        }),
      });

      if (!response.ok) {
        const error = await response.json();
        throw new Error(error.message || "Login failed");
      }

      const data: AuthResponse = await response.json();

      // Store authentication data
      localStorage.setItem("auth_token", data.token);
      localStorage.setItem("user_id", data.user.id);
      localStorage.setItem("tenant_id", data.tenant.id);
      localStorage.setItem("banking_type", data.tenant.banking_type);
      localStorage.setItem("user_roles", JSON.stringify(data.user.roles));
      localStorage.setItem("tenant_features", JSON.stringify(data.tenant.features_enabled));

      return Promise.resolve();
    } catch (error) {
      return Promise.reject(error);
    }
  },

  // Logout - clear local storage and revoke token
  logout: async () => {
    try {
      const token = localStorage.getItem("auth_token");
      
      if (token) {
        await fetch(`${API_BASE_URL}/auth/logout`, {
          method: "POST",
          headers: {
            "Authorization": `Bearer ${token}`,
            "Content-Type": "application/json",
          },
        });
      }
    } catch (error) {
      console.warn("Logout request failed:", error);
    } finally {
      // Clear all auth data regardless of API call result
      localStorage.removeItem("auth_token");
      localStorage.removeItem("user_id");
      localStorage.removeItem("tenant_id");
      localStorage.removeItem("banking_type");
      localStorage.removeItem("user_roles");
      localStorage.removeItem("tenant_features");
    }

    return Promise.resolve();
  },

  // Check if user is authenticated
  checkAuth: async () => {
    const token = localStorage.getItem("auth_token");
    
    if (!token) {
      return Promise.reject(new Error("No authentication token"));
    }

    try {
      const response = await fetch(`${API_BASE_URL}/auth/verify`, {
        method: "GET",
        headers: {
          "Authorization": `Bearer ${token}`,
        },
      });

      if (!response.ok) {
        throw new Error("Token verification failed");
      }

      return Promise.resolve();
    } catch (error) {
      // Clear invalid token
      localStorage.removeItem("auth_token");
      return Promise.reject(error);
    }
  },

  // Check user permissions for specific actions
  checkError: async (error) => {
    const status = error.status;
    
    if (status === 401 || status === 403) {
      localStorage.removeItem("auth_token");
      return Promise.reject(new Error("Authentication required"));
    }
    
    return Promise.resolve();
  },

  // Get current user identity
  getIdentity: async (): Promise<UserIdentity> => {
    const token = localStorage.getItem("auth_token");
    const userId = localStorage.getItem("user_id");
    
    if (!token || !userId) {
      return Promise.reject(new Error("No user identity available"));
    }

    try {
      const response = await fetch(`${API_BASE_URL}/auth/profile`, {
        method: "GET",
        headers: {
          "Authorization": `Bearer ${token}`,
        },
      });

      if (!response.ok) {
        throw new Error("Failed to get user profile");
      }

      const data = await response.json();
      
      return {
        id: data.user.id,
        fullName: data.user.full_name,
        avatar: data.user.avatar_url,
      };
    } catch (error) {
      return Promise.reject(error);
    }
  },

  // Get user permissions
  getPermissions: async () => {
    const roles = localStorage.getItem("user_roles");
    const tenantFeatures = localStorage.getItem("tenant_features");
    
    if (!roles || !tenantFeatures) {
      return Promise.reject(new Error("No permissions available"));
    }

    try {
      const userRoles = JSON.parse(roles);
      const features = JSON.parse(tenantFeatures);
      
      // Combine role permissions with tenant features
      const permissions = userRoles.reduce((acc: Record<string, boolean>, role: any) => {
        return { ...acc, ...role.permissions };
      }, {});
      
      return Promise.resolve({
        roles: userRoles.map((role: any) => role.role_name),
        permissions,
        features,
      });
    } catch (error) {
      return Promise.reject(error);
    }
  },
};

// Helper functions for permission checking
export const hasPermission = (permission: string): boolean => {
  try {
    const roles = localStorage.getItem("user_roles");
    if (!roles) return false;
    
    const userRoles = JSON.parse(roles);
    return userRoles.some((role: any) => role.permissions[permission] === true);
  } catch {
    return false;
  }
};

export const hasFeature = (feature: string): boolean => {
  try {
    const features = localStorage.getItem("tenant_features");
    if (!features) return false;
    
    const tenantFeatures = JSON.parse(features);
    return tenantFeatures[feature] === true;
  } catch {
    return false;
  }
};

export const getBankingType = (): "conventional" | "syariah" | "dual" => {
  return (localStorage.getItem("banking_type") as any) || "conventional";
};'

    generate_component "${file_path}" "${content}"
}

