// API configuration
const API_BASE_URL = process.env.NEXT_PUBLIC_API_BASE_URL || "http://localhost:4232/api";

// Multi-tenant headers
const getTenantHeaders = (): HeadersInit => {
  const token = localStorage.getItem("auth_token");
  const tenantId = localStorage.getItem("tenant_id");
  
  return {
    "Content-Type": "application/json",
    "Authorization": token ? `Bearer ${token}` : "",
    "X-Tenant-ID": tenantId || "",
  };
};

// HTTP client with tenant support
const httpClient = async (url: string, options: RequestInit = {}) => {
  const response = await fetch(url, {
    ...options,
    headers: {
      ...getTenantHeaders(),
      ...options.headers,
    },
  });

  if (!response.ok) {
    const error = await response.json().catch(() => ({ message: "Network error" }));
    throw new Error(error.message || `HTTP ${response.status}`);
  }

  return response;
};

// Multi-tenant data provider implementation
export const dataProvider: DataProvider = {
  getList: async (resource: string, params: GetListParams) => {
    const { page, perPage } = params.pagination || { page: 1, perPage: 25 };
    const { field, order } = params.sort || { field: "id", order: "ASC" };
    const query = {
      ...params.filter,
      _sort: field,
      _order: order,
      _start: (page - 1) * perPage,
      _end: page * perPage,
    };

    const url = `${API_BASE_URL}/${resource}?${stringify(query)}`;
    const response = await httpClient(url);
    const json = await response.json();

    return {
      data: json.data || [],
      total: json.total || 0,
    };
  },

  getOne: async (resource: string, params: GetOneParams) => {
    const url = `${API_BASE_URL}/${resource}/${params.id}`;
    const response = await httpClient(url);
    const json = await response.json();

    return {
      data: json.data,
    };
  },

  getMany: async (resource: string, params: { ids: any[] }) => {
    const query = {
      id: params.ids,
    };
    const url = `${API_BASE_URL}/${resource}?${stringify(query, { arrayFormat: "repeat" })}`;
    const response = await httpClient(url);
    const json = await response.json();

    return {
      data: json.data || [],
    };
  },

