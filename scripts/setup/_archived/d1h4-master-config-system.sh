# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
PURPLE='\033[0;35m'
CYAN='\033[0;36m'
NC='\033[0m' # No Color

# Logging functions
log_info() {
    echo -e "${BLUE}[INFO] $(date '+%Y-%m-%d %H:%M:%S') - $1${NC}" | tee -a "${LOG_FILE}"
}

log_error() {
    echo -e "${RED}[ERROR] $(date '+%Y-%m-%d %H:%M:%S') - $1${NC}" | tee -a "${LOG_FILE}" >&2
}

log_success() {
    echo -e "${GREEN}[SUCCESS] $(date '+%Y-%m-%d %H:%M:%S') - $1${NC}" | tee -a "${LOG_FILE}"
}

log_warn() {
    echo -e "${YELLOW}[WARN] $(date '+%Y-%m-%d %H:%M:%S') - $1${NC}" | tee -a "${LOG_FILE}"
}

log_section() {
    echo -e "\n${PURPLE}========================================${NC}" | tee -a "${LOG_FILE}"
    echo -e "${PURPLE}🎯 $1${NC}" | tee -a "${LOG_FILE}"
    echo -e "${PURPLE}========================================${NC}\n" | tee -a "${LOG_FILE}"
}

# Error handling
handle_error() {
    local exit_code=$?
    log_error "Script failed with exit code: ${exit_code}"
    log_error "Failed command: ${BASH_COMMAND}"
    log_error "Check the log file for details: ${LOG_FILE}"
    exit ${exit_code}
}

trap handle_error ERR

# Print banner
print_banner() {
    echo -e "${CYAN}"
    cat << 'EOF'
🚀 IFRS9 Platform - Master Configuration Management System
============================================================
EOF
    echo -e "${NC}"
    echo ""
    echo -e "${CYAN}Setting up comprehensive configuration management system...${NC}"
    echo -e "${CYAN}This includes environment validation, feature flags, and tenant configuration.${NC}"
    echo ""
}

# Validate prerequisites
validate_prerequisites() {
    log_section "CHECKING PREREQUISITES"
    
    # Check Node.js
    if ! command -v node &> /dev/null; then
        log_error "Node.js is not installed"
        exit 1
    fi
    
    local node_version=$(node --version | sed 's/v//')
    log_info "Node.js version: ${node_version}"
    
    # Check pnpm
    if ! command -v pnpm &> /dev/null; then
        log_error "pnpm is not installed. Install with: npm install -g pnpm"
        exit 1
    fi
    
    local pnpm_version=$(pnpm --version)
    log_info "pnpm version: ${pnpm_version}"
    
    # Check if previous authentication setup was completed
    if [[ ! -f "${PROJECT_ROOT}/packages/backend/src/core/services/auth/jwt.service.ts" ]]; then
        log_warn "Authentication system not found. Run d1h3-* scripts first."
    fi
    
    log_success "All prerequisites met"
}

