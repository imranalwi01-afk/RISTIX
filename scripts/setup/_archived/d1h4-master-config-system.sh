# Install dependencies
install_dependencies() {
    log_section "INSTALLING CONFIGURATION DEPENDENCIES"
    
    cd "${PROJECT_ROOT}"
    
    # Install backend dependencies
    log_info "Installing backend configuration dependencies..."
    cd packages/backend
    
    # Configuration-specific dependencies
    pnpm add winston zod class-validator class-transformer
    pnpm add --save-dev @types/node @types/winston
    
    log_success "Backend configuration dependencies installed"
    
    cd "${PROJECT_ROOT}"
}

# Run configuration setup scripts
run_configuration_scripts() {
    log_section "RUNNING CONFIGURATION SYSTEM GENERATION SCRIPTS"
    
    # Make all scripts executable
    chmod +x "${SCRIPT_DIR}"/*.sh
    
    # Run main configuration management setup
    log_info "Running main configuration management setup..."
    if "${SCRIPT_DIR}/d1h4-config-management-setup.sh"; then
        log_success "Configuration management setup completed"
    else
        log_error "Configuration management setup failed"
        exit 1
    fi
    
    # Run environment validation setup
    log_info "Running environment validation setup..."
    if "${SCRIPT_DIR}/d1h4-environment-validation.sh"; then
        log_success "Environment validation setup completed"
    else
        log_error "Environment validation setup failed"
        exit 1
    fi
    
    # Run feature flags setup
    log_info "Running feature flags setup..."
    if "${SCRIPT_DIR}/d1h4-feature-flags.sh"; then
        log_success "Feature flags setup completed"
    else
        log_error "Feature flags setup failed"
        exit 1
    fi
    
    # Run tenant configuration setup
    log_info "Running tenant configuration setup..."
    if "${SCRIPT_DIR}/d1h4-tenant-config.sh"; then
        log_success "Tenant configuration setup completed"
    else
        log_error "Tenant configuration setup failed"
        exit 1
    fi
}

