SELECT A.IA_ID,
A.ACCOUNT_ID,
A.EFF_INTEREST_RATE,
C.MOB,
C.PERIODE,
C.PRINCIPAL,
C.INTEREST,
C.PRINCIPAL + C.INTEREST AS INSTALLMENT,
C.COLLATERAL,
A.PO_RATE_1,
B.RR_RATE_1,
(C.PRINCIPAL + C.INTEREST + C.COLLATERAL) * A.PO_RATE_1/100 * B.RR_RATE_1/100 AS DEFAULT_1,
A.PO_RATE_2,
B.RR_RATE_2,
(C.PRINCIPAL + C.INTEREST + C.COLLATERAL) * A.PO_RATE_2/100 * B.RR_RATE_2/100 AS DEFAULT_2,
A.PO_RATE_3,
B.RR_RATE_3,
(C.PRINCIPAL + C.INTEREST + C.COLLATERAL) * A.PO_RATE_3/100 * B.RR_RATE_3/100 AS DEFAULT_3,
((C.PRINCIPAL + C.INTEREST + C.COLLATERAL) * A.PO_RATE_1/100 * B.RR_RATE_1/100) + ((C.PRINCIPAL + C.INTEREST + C.COLLATERAL) * A.PO_RATE_2/100 * B.RR_RATE_2/100) + ((C.PRINCIPAL + C.INTEREST + C.COLLATERAL) * A.PO_RATE_3/100 * B.RR_RATE_3/100) AS PW_AMT,
POWER(1/(1+A.EFF_INTEREST_RATE/100/12),C.MOB) AS DISCOUNT_FACTOR,
CAST(
(((C.PRINCIPAL + C.INTEREST + C.COLLATERAL) * A.PO_RATE_1/100 * B.RR_RATE_1/100) + ((C.PRINCIPAL + C.INTEREST + C.COLLATERAL) * A.PO_RATE_2/100 * B.RR_RATE_2/100) + ((C.PRINCIPAL + C.INTEREST + C.COLLATERAL) * A.PO_RATE_3/100 * B.RR_RATE_3/100)) 
 * (POWER(1/(1+A.EFF_INTEREST_RATE/100/12),C.MOB)) AS DECIMAL(32,6))  AS PV_AMT,
CAST (0 AS DECIMAL(32,6)) AS BEGINNING_BALANCE,
CAST (0 AS DECIMAL(32,6)) AS EIR_AMT,
CAST (0 AS DECIMAL(32,6)) AS ENDING_BALANCE,
'USER ID' AS CREATEDBY,
GETDATE() AS CREATEDDATE,
'USERHOST' AS CREATEDHOST 
INTO #TMP_IMP_IA_DETAIL
FROM FRS9_IMP_IA_HEADER A
INNER JOIN FRS9_IMP_IA_RR B
ON A.IA_ID = B.IA_ID 
INNER JOIN FRS9_IMP_IA_DCF C
ON A.IA_ID = C.IA_ID
AND C.PERIODE BETWEEN B.PERIOD_START AND B.PERIOD_END
WHERE A.ACCOUNT_ID = 999999 

DECLARE @V_START INT
DECLARE @V_END INT
DECLARE @NPV DECIMAL(32,6) = 0
DECLARE @BEGINNING_BALANCE FLOAT = 0
DECLARE @ENDING_BALANCE FLOAT = 0
DECLARE @EIR_AMT FLOAT = 0

SET @V_START = 1
SELECT @V_END = MAX(MOB), @NPV = SUM(PV_AMT) FROM #TMP_IMP_IA_DETAIL

UPDATE FRS9_IMP_IA_HEADER 
SET PV_DCF_AMT=@NPV,
ECL_IA_AMT = EAD_AMT - @NPV 
WHERE ACCOUNT_ID = 999999
--PRINT @NPV

WHILE (@V_START <= @V_END) 
BEGIN 
 
SET @BEGINNING_BALANCE = CASE WHEN @V_START = 1 THEN @NPV ELSE @ENDING_BALANCE END
SET @EIR_AMT = @BEGINNING_BALANCE * 12/100/12
SELECT @ENDING_BALANCE = @BEGINNING_BALANCE + @EIR_AMT - PW_AMT FROM #TMP_IMP_IA_DETAIL WHERE MOB = @V_START

--PRINT @BEGINNING_BALANCE

UPDATE #TMP_IMP_IA_DETAIL 
SET BEGINNING_BALANCE = @BEGINNING_BALANCE,
EIR_AMT = @EIR_AMT,
ENDING_BALANCE = @ENDING_BALANCE
WHERE MOB = @V_START
SET @V_START = @V_START + 1
END

DELETE FRS9_IMP_IA_DETAIL WHERE ACCOUNT_ID = 999999

