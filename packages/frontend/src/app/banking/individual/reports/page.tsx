'use client';

import React, { useState, useEffect } from 'react';
import { Container, Typography, Box, Card, CardContent, CircularProgress, Chip } from '@mui/material';
import PageHeader from '@/components/banking/shared/PageHeader';
import { DataGrid, GridColDef } from '@mui/x-data-grid';
import { FullstackIndicator } from '@/components/common/feedback/FullstackIndicator';
import { api } from '@/services/api';

const columns: GridColDef[] = [
  { field: 'reportPeriod', headerName: 'Period', width: 150 },
  { field: 'reportType', headerName: 'Report Type', width: 250 },
  { field: 'generatedBy', headerName: 'Generated By', width: 200 },
  { field: 'createdAt', headerName: 'Generated At', width: 200, valueFormatter: (value: any) => new Date(value).toLocaleString() },
  { 
    field: 'status', 
    headerName: 'Status', 
    width: 150,
    renderCell: (params) => {
      const color = params.value === 'READY' ? 'success' : params.value === 'PENDING' ? 'warning' : 'error';
      return <Chip label={params.value} color={color} size="small" />;
    }
  },
  { field: 'totalRecords', headerName: 'Records', width: 150 },
];

export default function IndividualReportsPage() {
  const [rows, setRows] = useState([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    const fetchData = async () => {
      try {
        setLoading(true);
        const response = await api.individualImpairment.getReports();
        if (response.success && response.data) {
          setRows(response.data);
        }
      } catch (error) {
        console.error('Failed to fetch reports:', error);
      } finally {
        setLoading(false);
      }
    };
    fetchData();
  }, []);

  return (
    <Container maxWidth="xl">
      <FullstackIndicator />
      <PageHeader
        title="List of Individual Reports"
        subtitle="Generated impairment reports and archives"
      />
      <Card>
        <CardContent>
           <Box sx={{ height: 500, width: '100%' }}>
            {loading ? (
               <Box display="flex" justifyContent="center" alignItems="center" height="100%">
                 <CircularProgress />
               </Box>
            ) : (
                <DataGrid
                  rows={rows}
                  columns={columns}
                  pageSizeOptions={[10, 25]}
                />
            )}
          </Box>
        </CardContent>
      </Card>
    </Container>
  );
}
