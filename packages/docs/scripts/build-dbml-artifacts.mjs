import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dbmlDir = join(process.cwd(), 'static', 'dbml')

const functionalSourcePath = join(dbmlDir, 'ifrs9-functional-legacy.dbml')
const rbacSourcePath = join(dbmlDir, 'ifrs9-rbac-auth.dbml')
const publishPath = join(dbmlDir, 'ifrs9-dbdocs-publish.dbml')
const tenantDbdocsPath = join(dbmlDir, 'ifrspro_tenant_iaf.dbml')
const platformDbdocsPath = join(dbmlDir, 'ifrspro_platform_admin.dbml')

const splitTargets = [
  {
    id: 'core-master',
    title: 'IFRS9 Functional - Core/Master',
    match: (tableName) => {
      return !tableName.startsWith('frs9_param_')
        && tableName !== 'frs9_ecl_model_mapping'
        && !tableName.startsWith('frs9_imp_ca_')
        && !tableName.startsWith('frs9_imp_ia_')
        && !tableName.startsWith('stg_')
        && !tableName.startsWith('tmp_')
    },
  },
  {
    id: 'parameters',
    title: 'IFRS9 Functional - Parameters',
    match: (tableName) => tableName.startsWith('frs9_param_') || tableName === 'frs9_ecl_model_mapping',
  },
  {
    id: 'impairment-collective',
    title: 'IFRS9 Functional - Impairment Collective',
    match: (tableName) => tableName.startsWith('frs9_imp_ca_'),
  },
  {
    id: 'impairment-individual',
    title: 'IFRS9 Functional - Impairment Individual',
    match: (tableName) => tableName.startsWith('frs9_imp_ia_'),
  },
  {
    id: 'staging-temp',
    title: 'IFRS9 Functional - Staging/Temp',
    match: (tableName) => tableName.startsWith('stg_') || tableName.startsWith('tmp_'),
  },
]

function parseTables(dbmlText) {
  const headerLines = []
  const tableBlocks = []
  const refBlocks = []

  const lines = dbmlText.split('\n')
  let i = 0

  while (i < lines.length && !lines[i].startsWith('Table ')) {
    if (lines[i].trim().length > 0) {
      headerLines.push(lines[i])
    }
    i += 1
  }

  while (i < lines.length) {
    const line = lines[i]
    if (line.startsWith('Ref: ')) {
      refBlocks.push(line)
      i += 1
      continue
    }

    if (!line.startsWith('Table ')) {
      i += 1
      continue
    }

    const block = [line]
    let depth = (line.match(/\{/g) || []).length - (line.match(/\}/g) || []).length
    i += 1

    while (i < lines.length) {
      const currentLine = lines[i]
      block.push(currentLine)
      depth += (currentLine.match(/\{/g) || []).length
      depth -= (currentLine.match(/\}/g) || []).length
      i += 1
      if (depth <= 0) {
        break
      }
    }

    const firstLine = block[0]
    const match = firstLine.match(/^Table\s+([A-Za-z0-9_]+)\.([A-Za-z0-9_]+)\s+/)
    if (!match) {
      throw new Error(`Unable to parse table name from line: ${firstLine}`)
    }

    const schemaName = match[1]
    const tableName = match[2]

    tableBlocks.push({
      schemaName,
      tableName,
      fullName: `${schemaName}.${tableName}`,
      text: `${block.join('\n')}\n`,
    })
  }

  return {
    header: headerLines.join('\n').trim(),
    tableBlocks,
    refBlocks,
  }
}

function buildFile({ title, sourceName, tables }) {
  const header = [
    `// ${title}`,
    `// Generated by scripts/build-dbml-artifacts.mjs from ${sourceName}`,
    '',
  ].join('\n')

  return `${header}${tables.map((t) => `${t.text}\n`).join('')}`
}

const functionalText = readFileSync(functionalSourcePath, 'utf8')
const rbacText = readFileSync(rbacSourcePath, 'utf8')

const { tableBlocks } = parseTables(functionalText)
const { tableBlocks: rbacTables, refBlocks: rbacRefs } = parseTables(rbacText)

const splitOutputs = []

for (const target of splitTargets) {
  const tables = tableBlocks.filter((t) => target.match(t.tableName))

  const content = buildFile({
    title: target.title,
    sourceName: 'ifrs9-functional-legacy.dbml',
    tables,
  })

  const filename = `ifrs9-functional-${target.id}.dbml`
  const outPath = join(dbmlDir, filename)
  writeFileSync(outPath, content)

  splitOutputs.push({ filename, count: tables.length, content })
}

const assignedCount = splitOutputs.reduce((sum, item) => sum + item.count, 0)
if (assignedCount !== tableBlocks.length) {
  throw new Error(`Split assignment mismatch: assigned ${assignedCount}, source ${tableBlocks.length}`)
}

const publishHeader = [
  '// IFRS9 IAF - DBDocs Publish Artifact',
  '// Generated by scripts/build-dbml-artifacts.mjs',
  `// Includes: ifrs9-rbac-auth.dbml + ${splitOutputs.length} functional domain files`,
  '',
].join('\n')

const publishBody = [
  rbacText.trim(),
  ...splitOutputs.map((item) => item.content.trim()),
].join('\n\n')

writeFileSync(publishPath, `${publishHeader}${publishBody}\n`)

const splitTableBlocks = splitOutputs.flatMap((item) => parseTables(item.content).tableBlocks)

const tenantRbacTables = rbacTables.filter((t) => t.schemaName !== 'platform_admin')
const platformRbacTables = rbacTables.filter((t) => t.schemaName === 'platform_admin')

function parseRefTables(refLine) {
  const m = refLine.match(/^Ref:\s+([A-Za-z0-9_]+\.[A-Za-z0-9_]+)\.[A-Za-z0-9_]+\s*>\s*([A-Za-z0-9_]+\.[A-Za-z0-9_]+)\.[A-Za-z0-9_]+/)
  if (!m) return null
  return { leftTable: m[1], rightTable: m[2] }
}

function filterRefs(refs, allowedTables) {
  const allowedSet = new Set(allowedTables.map((t) => t.fullName))
  return refs.filter((ref) => {
    const parsed = parseRefTables(ref)
    if (!parsed) return false
    return allowedSet.has(parsed.leftTable) && allowedSet.has(parsed.rightTable)
  })
}

function buildDbdocsFile({ dbName, tableBlocks, refBlocks }) {
  const lines = [
    `// DBDocs artifact for ${dbName}`,
    '// Generated by scripts/build-dbml-artifacts.mjs',
    '',
    `Project ${dbName} {`,
    "  database_type: 'PostgreSQL'",
    `  Note: 'Logical DBML view for ${dbName}.'`,
    '}',
    '',
    ...tableBlocks.map((t) => t.text.trim()),
  ]

  if (refBlocks.length > 0) {
    lines.push('')
    lines.push(...refBlocks)
  }

  return `${lines.join('\n\n')}\n`
}

const tenantTables = [...tenantRbacTables, ...splitTableBlocks]
const tenantRefs = filterRefs(rbacRefs, tenantTables)
const platformRefs = filterRefs(rbacRefs, platformRbacTables)

writeFileSync(tenantDbdocsPath, buildDbdocsFile({
  dbName: 'ifrspro_tenant_iaf',
  tableBlocks: tenantTables,
  refBlocks: tenantRefs,
}))

writeFileSync(platformDbdocsPath, buildDbdocsFile({
  dbName: 'ifrspro_platform_admin',
  tableBlocks: platformRbacTables,
  refBlocks: platformRefs,
}))

const summary = splitOutputs.map((item) => `${item.filename}: ${item.count} tables`).join(', ')
console.log(`Generated split DBML, shared publish artifact, and DB-specific artifacts. ${summary}. total=${tableBlocks.length}; tenant_tables=${tenantTables.length}; platform_tables=${platformRbacTables.length}`)
